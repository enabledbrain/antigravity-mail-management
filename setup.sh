#!/usr/bin/env bash
# ==============================================================================
# antigravity-mail-management - Interactive Setup Script (macOS / Linux)
# ==============================================================================
set -e
cd "$(dirname "$0")"

echo "=========================================================="
echo "📬 antigravity-mail-management 初期セットアップウィザード"
echo "=========================================================="
echo ""

# 1. Thunderbird プロファイルの自動探索
echo "🔍 [1/4] Thunderbird プロファイルを探索中..."
PROFILE_CANDIDATE=""

POSSIBLE_DIRS=(
  "$HOME/Library/Thunderbird/Profiles"
  "$HOME/Library/CloudStorage/Dropbox/appData/Thunderbird/Profiles"
  "$HOME/Library/Application Support/Thunderbird/Profiles"
  "$HOME/.thunderbird"
)

for pdir in "${POSSIBLE_DIRS[@]}"; do
  if [ -d "$pdir" ]; then
    # 直近で更新されたプロファイルディレクトリを取得
    LATEST=$(ls -td "$pdir"/*.* 2>/dev/null | head -n 1 || true)
    if [ -n "$LATEST" ] && [ -d "$LATEST" ]; then
      PROFILE_CANDIDATE="$LATEST"
      break
    fi
  fi
done

if [ -n "$PROFILE_CANDIDATE" ]; then
  echo "✅ プロファイル候補を検出しました: $PROFILE_CANDIDATE"
  read -p "このプロファイルを使用しますか？ [Y/n]: " USE_DETECTED
  USE_DETECTED=${USE_DETECTED:-Y}
  if [[ "$USE_DETECTED" =~ ^[Yy]$ ]]; then
    SELECTED_PROFILE="$PROFILE_CANDIDATE"
  fi
fi

if [ -z "$SELECTED_PROFILE" ]; then
  read -p "Thunderbird のプロファイル絶対パスを入力してください: " SELECTED_PROFILE
fi

# 2. .env ファイルの作成
echo ""
echo "📝 [2/4] .env ファイルを作成中..."
cat <<EOF > .env
# Auto-generated by setup.sh
THUNDERBIRD_PROFILE_PATH=$SELECTED_PROFILE
EOF
echo "✅ .env を作成しました。"

# 3. config.json の作成
echo ""
echo "⚙️  [3/4] config.json を設定中..."
if [ ! -f config.json ]; then
  cp config.example.json config.json
  echo "ℹ️  config.json を作成しました。"
fi

read -p "Slack Incoming Webhook URL を入力してください (スキップは Enter): " SLACK_WEBHOOK
if [ -n "$SLACK_WEBHOOK" ]; then
  # python で json を安全に更新
  python3 -c "
import json
with open('config.json', 'r', encoding='utf-8') as f:
    cfg = json.load(f)
cfg['slack']['webhook_url'] = '$SLACK_WEBHOOK'
with open('config.json', 'w', encoding='utf-8') as f:
    json.dump(cfg, f, indent=2, ensure_ascii=False)
" 2>/dev/null || true
  echo "✅ Slack Webhook URL を保存しました。"
fi

# 4. 初回キャッチアップ（過去メールの一括既読化）
echo ""
echo "🚀 [4/4] 初回キャッチアップ（過去メールの一括インデックス化）を実行しますか？"
echo "※ 過去メールを既読として DB/Meilisearch に登録し、Slack への大量誤通知を防ぎます。"
read -p "実行しますか？ [Y/n]: " RUN_CATCHUP
RUN_CATCHUP=${RUN_CATCHUP:-Y}

if [[ "$RUN_CATCHUP" =~ ^[Yy]$ ]]; then
  echo "⚡ キャッチアップを実行中..."
  ./run.sh --init-catchup
fi

echo ""
echo "=========================================================="
echo "🎉 セットアップが完了しました！"
echo "・テスト実行: ./run.sh --dry-run"
echo "・本番実行:   ./run.sh"
echo "・メール検索: ./run.sh --search \"キーワード\""
echo "=========================================================="
